/** Gantikan {n}, {p}, {amt} dsb. dengan nilai sebenar. */
function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] === undefined ? `{${k}}` : String(vars[k]),
  );
}

/**
 * Terjemah satu kunci.
 *
 * Jika kunci tiada dalam kamus, ia dipulangkan APA ADANYA  -  supaya teks yang
 * hilang kelihatan serta-merta semasa membina, bukan bertukar menjadi kunci
 * kosong yang senyap.
 */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const entry = DICT[key];
  if (!entry) return key;
  return interpolate(entry[lang], vars);
}

/** Terjemah status temujanji mentah dari API. */
export function translateStatus(lang: Lang, status: string): string {
  const map: Record<string, string> = {
    booked: "st.booked", confirmed: "st.confirmed", "checked-in": "st.checkedIn",
    waiting: "st.waiting", called: "st.called", "in-progress": "st.inProgress",
    completed: "st.completed", cancelled: "st.cancelled", "no-show": "st.noShow",
  };
  const key = map[status];
  return key ? translate(lang, key) : status;
}
