import { Injectable, Logger } from '@nestjs/common';
import { and, eq, isNull, sql, SQL } from 'drizzle-orm';
import { DbContextService } from '../../../core/auth/db-context.service';
import { Principal } from '../../../core/auth/principal';
import { ForbiddenError } from '../../../shared/errors/errors';
import { AiPolicyPort } from '../../../shared/ports/ai-policy.port';
import { FinanceReadPort } from '../../../shared/ports/finance.read-port';
import { AppointmentsReadPort } from '../../../shared/ports/appointments.read-port';
import { patients, encounters, treatmentCosts, branches, bukkuSyncRecords } from '../../../infrastructure/database/schema';
import {
  buildInsights,
  type InsightCard,
  type BranchNoShowRow,
  type UninvoicedEncounterRow,
} from '../domain/insight-rules';
import { previousPeriodRange, isReportPeriod, type ReportPeriod } from '../../reports/domain/period-resolver';

/**
 * InsightsService — Phase C: proactive insight SCAN.
 *
 * The dental-erp AIInsight pattern, with this repo's discipline:
 * - Insights are COMPUTED by deterministic rules (insight-rules.ts), not
 *   generated by a model. No MiniMax call here at all — a card that exists
 *   can later be narrated by the model, but the finding itself is code.
 * - Same shape as finance's generateRadar: scan real rows → fire rules →
 *   return cards. Nothing is persisted yet (Phase C is read-only scan);
 *   persistence + dismissal arrive with the UI feedback loop.
 * - Scope: HQ-only. The dashboard pulse is HQ-only; branch managers get the
 *   branch view later, not in this first cut.
 */
@Injectable()
export class InsightsService {
  private readonly logger = new Logger('InsightsService');

  constructor(
    private readonly policy: AiPolicyPort,
    private readonly dbCtx: DbContextService,
    private readonly finance: FinanceReadPort,
    private readonly appointments: AppointmentsReadPort,
  ) {}

  async scan(principal: Principal, rawPeriod?: string): Promise<{ cards: InsightCard[] }> {
    if (principal.role !== 'hq') throw new ForbiddenError('Insights scan is HQ-only');

    /* Policy gate, same as the analyst: insights-ai is DRAFT-ONLY, so the
     * gate asks canDraft. Paused agent → no scan, no data read. */
    const allowed = await this.policy.canDraft(principal, {
      agentKey: 'insights-ai',
      domain: 'reports',
      actionKey: 'insights.scan',
    });
    if (!allowed) throw new ForbiddenError('Agen Insights AI tidak aktif (paused/registered) di AI Manager');

    const period: ReportPeriod = isReportPeriod(rawPeriod) ? rawPeriod : '30D';
    const now = new Date();
    const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());

    const from = new Date(today);
    from.setDate(from.getDate() - (period === '12M' ? 365 : period === '90D' ? 90 : period === '7D' ? 7 : 30));
    const iso = (d: Date) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
    const fromIso = iso(from);
    const toIso = iso(today);
    const prev = previousPeriodRange(period, now);

    /* No-show evaluation must only cover CLOSED days (FASA 1G lesson inside
     * AppointmentsReadPort itself): evaluating "today" would accuse patients
     * who are merely late. Evaluate through yesterday. */
    const evalTo = iso(new Date(today.getTime() - 86_400_000));

    return this.dbCtx.runAs(principal, async (tx) => {
      /* BERURUTAN, bukan Promise.all — one MySQL transaction holds ONE
       * connection (dashboard pulse lesson). */
      const revenueNow = Number(await this.finance.revenueTotal(tx as never, principal.orgId, { from: fromIso, to: toIso }));
      const revenuePrev = Number(await this.finance.revenueTotal(tx as never, principal.orgId, { from: prev.from, to: prev.to }));

      const statusRows = await this.appointments.statusByBranch(tx as never, principal.orgId, fromIso, evalTo);
      const branchNoShow = await this.branchNoShow(tx as never, principal.orgId, statusRows, fromIso, evalTo);

      const uninvoiced = await this.uninvoicedEncounters(tx as never, principal.orgId, fromIso, toIso);
      const bukkuLastSyncedAt = await this.lastBukkuSync(tx as never, principal.orgId);

      const cards = buildInsights({
        branchNoShow,
        currentRevenue: revenueNow,
        previousRevenue: revenuePrev,
        periodLabel: period === '12M' ? '12 bulan lepas' : period === '90D' ? '90 hari lepas' : period === '7D' ? '7 hari lepas' : '30 hari lepas',
        uninvoiced,
        bukkuLastSyncedAt,
        now,
      });
      return { cards };
    });
  }

  /** statusByBranch rows → per-branch booked/completed/noShow with names. */
  private async branchNoShow(
    tx: Parameters<Parameters<DbContextService['runAs']>[1]>[0],
    orgId: string,
    statusRows: Array<{ branchId: string; status: string; n: number }>,
    _from: string,
    _to: string,
  ): Promise<BranchNoShowRow[]> {
    /* booked = pipeline statuses; completed and no-show map directly. */
    const byBranch = new Map<string, { booked: number; completed: number; noShow: number }>();
    for (const r of statusRows) {
      const b = byBranch.get(r.branchId) ?? { booked: 0, completed: 0, noShow: 0 };
      if (r.status === 'completed') b.completed += Number(r.n);
      else if (r.status === 'no-show') b.noShow += Number(r.n);
      else b.booked += Number(r.n);
      byBranch.set(r.branchId, b);
    }
    const names = await tx.select({ id: branches.id, name: branches.fullName })
      .from(branches).where(and(eq(branches.orgId, orgId), isNull(branches.deletedAt)));
    const nameOf = new Map(names.map((b) => [b.id, b.name]));
    return [...byBranch.entries()].map(([branchId, v]) => ({
      branchId,
      branchName: nameOf.get(branchId) ?? branchId,
      ...v,
    }));
  }

  /**
   * Completed encounters in range with NO treatment_costs row. The clinical×
   * finance seam: work done, money never recorded.
   */
  private async uninvoicedEncounters(
    tx: Parameters<Parameters<DbContextService['runAs']>[1]>[0],
    orgId: string,
    from: string,
    to: string,
  ): Promise<UninvoicedEncounterRow[]> {
    const rows = await tx
      .select({
        encounterId: encounters.id,
        patientName: patients.name,
        branchName: branches.fullName,
        completedAt: encounters.completedAt,
      })
      .from(encounters)
      .innerJoin(patients, eq(patients.id, encounters.patientId))
      .innerJoin(branches, eq(branches.id, encounters.branchId))
      .where(and(
        eq(encounters.orgId, orgId),
        isNull(encounters.deletedAt),
        eq(encounters.status, 'completed') as SQL,
        sql`DATE(${encounters.completedAt}) >= ${from}`,
        sql`DATE(${encounters.completedAt}) <= ${to}`,
        sql`NOT EXISTS (SELECT 1 FROM ${treatmentCosts} WHERE ${treatmentCosts.encounterId} = ${encounters.id} AND ${treatmentCosts.deletedAt} IS NULL)`,
      ))
      .orderBy(sql`${encounters.completedAt} DESC`)
      .limit(50);
    return rows.map((r) => ({
      encounterId: r.encounterId,
      patientName: r.patientName ?? 'Pesakit',
      branchName: r.branchName,
      completedAt: r.completedAt ? new Date(r.completedAt).toISOString().slice(0, 10) : '',
    }));
  }

  private async lastBukkuSync(
    tx: Parameters<Parameters<DbContextService['runAs']>[1]>[0],
    orgId: string,
  ): Promise<string | null> {
    /* bukku_sync_records.last_synced_at is per-entity; the freshest row is
     * the honest "when did we last hear from Bukku". */
    const rows = await tx.select({ lastSyncedAt: sql<Date | null>`MAX(${bukkuSyncRecords.lastSyncedAt})` })
      .from(bukkuSyncRecords)
      .where(eq(bukkuSyncRecords.orgId, orgId));
    const v = rows[0]?.lastSyncedAt;
    return v instanceof Date ? v.toISOString() : typeof v === 'string' ? v : null;
  }
}
